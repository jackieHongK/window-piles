"""Bakes the app's walnut (the organizer's bookmark and tray, and the "월넛 원목" card material) from the
same scanned veneer the 3D unboxing uses, so the wood on screen and in the renders is one wood.

Source: Poly Haven "Black Walnut Veneer 02" (CC0), color-corrected to the oil finish by the unboxing
PoC: marketing/unboxing/walnut_diff.jpg (1024 x 512, about 4 px per mm, grain along x).

The tile is the scan at half size (1 px per DIP), made seamless both ways by cross-fading its edges,
stored as brightness only; the color comes from a dark-to-light ramp fitted to the scan (walnut's color
varies almost only along that line), so it is a quarter of an RGB tile.

Writes:
  src/ui/walnut_data.inc   kWalnutW x kWalnutH bytes + the ramp's two ends

Usage (needs Pillow and numpy):
  python scripts/gen_walnut.py [path to walnut_diff.jpg]
"""
import os
import sys

import numpy as np
from PIL import Image

W, H = 448, 224          # tile, px (= DIP at 100%)
BLEND_X, BLEND_Y = 64, 32  # cross-faded edges


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'marketing', 'unboxing', 'walnut_diff.jpg')
    img = Image.open(src).convert('RGB').resize((W + BLEND_X, H + BLEND_Y), Image.LANCZOS)
    rgb = np.asarray(img).astype(np.float64)

    # Seamless: the extra columns/rows past the tile fade into its first ones.
    t = np.linspace(0, 1, BLEND_X)[None, :, None]
    rgb[:, :BLEND_X] = rgb[:, :BLEND_X] * t + rgb[:, W:W + BLEND_X] * (1 - t)
    rgb = rgb[:, :W]
    t = np.linspace(0, 1, BLEND_Y)[:, None, None]
    rgb[:BLEND_Y] = rgb[:BLEND_Y] * t + rgb[H:H + BLEND_Y] * (1 - t)
    rgb = rgb[:H]

    # Brightness, stretched to 0..255, and the color at each end of that range (least squares per channel).
    lum = rgb @ np.array([0.2126, 0.7152, 0.0722])
    lo, hi = np.percentile(lum, 0.2), np.percentile(lum, 99.8)
    v = np.clip((lum - lo) / (hi - lo), 0, 1)
    A = np.stack([np.ones(v.size), v.ravel()], axis=1)
    coef, *_ = np.linalg.lstsq(A, rgb.reshape(-1, 3), rcond=None)
    dark, light = np.clip(coef[0], 0, 255), np.clip(coef[0] + coef[1], 0, 255)
    data = np.round(v * 255).astype(np.uint8)

    out = os.path.join(root, 'src', 'ui', 'walnut_data.inc')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by scripts/gen_walnut.py from the scanned walnut veneer (do not edit).\n')
        f.write(f'constexpr int kWalnutW = {W}, kWalnutH = {H};  // seamless both ways, grain along x\n')
        f.write('constexpr COLORREF kWalnutDark = RGB(%d, %d, %d), kWalnutLight = RGB(%d, %d, %d);  // brightness 0 and 255\n'
                % (*np.round(dark).astype(int), *np.round(light).astype(int)))
        f.write('constexpr unsigned char kWalnut[] = {\n')
        flat = data.ravel()
        for i in range(0, flat.size, 32):
            f.write('    ' + ','.join(str(b) for b in flat[i:i + 32]) + ',\n')
        f.write('};\n')
    print(f'{out}: {W}x{H}, dark {np.round(dark).astype(int)}, light {np.round(light).astype(int)}')


if __name__ == '__main__':
    main()
