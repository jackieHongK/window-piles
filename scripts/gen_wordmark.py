"""Outlines the Stack Neverflow wordmark (brand board spec) so the app and the brand assets don't
depend on the font:  lowercase "stack neverflow", Bricolage Grotesque, opsz 96, "stack" weight 380,
"neverflow" weight 760, letter-spacing -0.04em.

Font: Bricolage Grotesque (SIL Open Font License 1.1), google/fonts ofl/bricolagegrotesque,
file "BricolageGrotesque[opsz,wdth,wght].ttf" (git blob 9a4ca271ff84357bb8f8830ce71b85ea3571f731).
The font itself is not in this repo; outlining a logo is allowed by the OFL.

Writes:
  assets/brand/wordmark.svg    ink (#1A1917) on transparent, tight box, baseline at the bottom
  src/ui/wordmark_data.inc     flattened contours for Canvas (font units, y up, baseline 0)

Usage (needs fonttools and uharfbuzz):
  python scripts/gen_wordmark.py <path to the .ttf>
"""
import os
import sys

import uharfbuzz as hb
from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

RUNS = [("stack", 380), (" ", 400), ("neverflow", 760)]  # the space inherits the normal weight
OPSZ, WDTH, TRACKING = 96, 100, -0.04
CURVE_STEPS = 8  # segments per quadratic curve when flattening


class FlattenPen(BasePen):
    """Collects contours as polylines (quadratics flattened), offset by (dx, 0)."""

    def __init__(self, glyph_set, dx):
        super().__init__(glyph_set)
        self.dx, self.contours, self.cur = dx, [], []

    def _moveTo(self, p):
        self.cur = [(p[0] + self.dx, p[1])]

    def _lineTo(self, p):
        self.cur.append((p[0] + self.dx, p[1]))

    def _qCurveToOne(self, p1, p2):
        (x0, y0) = (self.cur[-1][0] - self.dx, self.cur[-1][1])
        for i in range(1, CURVE_STEPS + 1):
            t = i / CURVE_STEPS
            a, b, c = (1 - t) ** 2, 2 * (1 - t) * t, t * t
            self.cur.append((a * x0 + b * p1[0] + c * p2[0] + self.dx, a * y0 + b * p1[1] + c * p2[1]))

    def _curveToOne(self, p1, p2, p3):  # TrueType fonts don't use cubics, but be safe
        (x0, y0) = (self.cur[-1][0] - self.dx, self.cur[-1][1])
        for i in range(1, CURVE_STEPS + 1):
            t = i / CURVE_STEPS
            a, b, c, d = (1 - t) ** 3, 3 * (1 - t) ** 2 * t, 3 * (1 - t) * t * t, t ** 3
            self.cur.append((a * x0 + b * p1[0] + c * p2[0] + d * p3[0] + self.dx,
                             a * y0 + b * p1[1] + c * p2[1] + d * p3[1]))

    def _closePath(self):
        if len(self.cur) > 2:
            self.contours.append(self.cur)
        self.cur = []

    _endPath = _closePath


def main():
    font_path = sys.argv[1]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    tt = TTFont(font_path)
    upem = tt["head"].unitsPerEm
    blob = hb.Blob.from_file_path(font_path)
    contours, x = [], 0.0
    for text, weight in RUNS:
        loc = {"opsz": OPSZ, "wdth": WDTH, "wght": weight}
        font = hb.Font(hb.Face(blob))
        font.set_variations(loc)
        buf = hb.Buffer()
        buf.add_str(text)
        buf.guess_segment_properties()
        hb.shape(font, buf, {"kern": True, "liga": False})
        glyph_set = tt.getGlyphSet(location=loc)
        order = tt.getGlyphOrder()
        for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
            pen = FlattenPen(glyph_set, x + pos.x_offset)
            glyph_set[order[info.codepoint]].draw(pen)
            contours += pen.contours
            x += pos.x_advance + TRACKING * upem  # CSS letter-spacing: after every character

    xs = [p[0] for c in contours for p in c]
    ys = [p[1] for c in contours for p in c]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)

    # SVG: y down, tight box.
    d = " ".join("M" + " L".join(f"{px - x0:.1f},{y1 - py:.1f}" for px, py in c) + " Z" for c in contours)
    os.makedirs(os.path.join(root, "assets", "brand"), exist_ok=True)
    with open(os.path.join(root, "assets", "brand", "wordmark.svg"), "w", encoding="utf-8", newline="\n") as f:
        f.write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {x1 - x0:.1f} {y1 - y0:.1f}">\n'
                f'  <title>stack neverflow</title>\n'
                f'  <path fill="#1A1917" d="{d}"/>\n</svg>\n')

    # C++: one flat point list (rounded font units, relative to the box's left and the baseline) and
    # the index where each contour starts.
    pts, starts = [], []
    for c in contours:
        starts.append(len(pts))
        pts += [(round(px - x0), round(py)) for px, py in c]
    with open(os.path.join(root, "src", "ui", "wordmark_data.inc"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by scripts/gen_wordmark.py: the outlined \"stack neverflow\" wordmark (do not edit).\n")
        f.write(f"constexpr int kWordmarkWidth = {round(x1 - x0)}, kWordmarkTop = {round(y1)}, "
                f"kWordmarkBottom = {round(y0)};  // font units ({upem}/em), y up, baseline 0\n")
        f.write(f"constexpr int kWordmarkContours[] = {{{', '.join(map(str, starts))}}};\n")
        f.write("constexpr short kWordmarkPoints[][2] = {\n")
        for i in range(0, len(pts), 8):
            f.write("    " + ", ".join(f"{{{px}, {py}}}" for px, py in pts[i:i + 8]) + ",\n")
        f.write("};\n")
    print(f"{len(contours)} contours, {len(pts)} points, box {x1 - x0:.0f} x {y1 - y0:.0f} units ({upem}/em)")


if __name__ == "__main__":
    main()
